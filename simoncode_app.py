def build_questions():
    """Shuffle each pool and take the first few from each, easy -> medium -> hard."""
    easy = easy_questions.copy()
    medium = medium_questions.copy()
    hard = hard_questions.copy()
    random.shuffle(easy)
    random.shuffle(medium)
    random.shuffle(hard)

    picked = (
        easy[: QUESTIONS_PER_TIER["easy"]]
        + medium[: QUESTIONS_PER_TIER["medium"]]
        + hard[: QUESTIONS_PER_TIER["hard"]]
    )
    # Never have more questions than prize levels
    return [dict(q) for q in picked[: len(PRIZES) - 1]]


# ----------------------------------------------------------------------------
# Session state
# ----------------------------------------------------------------------------
def init_state():
    defaults = {
        "phase": "setup",          # setup -> playing -> locked -> game_over
        "name": "",
        "questions": [],
        "question_number": 0,
        "money_won": 0,
        "fifty_used": False,
        "audience_used": False,
        "hidden": [],              # option indexes removed by 50:50 on the current question
        "audience": None,          # {option_index: percent} for the current question
        "chosen": None,
        "feedback": "",
        "end_kind": "",            # "wrong", "walk" or "won"
        "end_message": "",
    }
    for key, value in defaults.items():
        if key not in st.session_state:
            st.session_state[key] = value


def reset_question_state():
    st.session_state.hidden = []
    st.session_state.audience = None
    st.session_state.chosen = None


def start_game(name):
    st.session_state.name = name
    st.session_state.questions = build_questions()
    st.session_state.question_number = 0
    st.session_state.money_won = 0
    st.session_state.fifty_used = False
    st.session_state.audience_used = False
    st.session_state.feedback = ""
    st.session_state.end_kind = ""
    st.session_state.end_message = ""
    reset_question_state()
    st.session_state.phase = "playing"


def current_question():
    return st.session_state.questions[st.session_state.question_number]


# ----------------------------------------------------------------------------
# Actions (used as button callbacks)
# ----------------------------------------------------------------------------
def use_fifty():
    """50:50 - keep the correct answer plus one random wrong answer (this question only)."""
    if st.session_state.fifty_used:
        return
    q = current_question()
    wrong_idxs = [i for i in range(4) if i != q["correct"]]
    keep_wrong = random.choice(wrong_idxs)
    st.session_state.hidden = [i for i in wrong_idxs if i != keep_wrong]
    st.session_state.fifty_used = True


def use_audience():
    """Ask the audience - percentages always add up to 100."""
    if st.session_state.audience_used:
        return
    q = current_question()
    correct = q["correct"]
    visible = [i for i in range(4) if i not in st.session_state.hidden]

    if len(visible) == 2:
        # After 50:50 the audience only chooses between the two remaining answers
        correct_pct = random.randint(60, 85)
        other = [i for i in visible if i != correct][0]
        percents = {correct: correct_pct, other: 100 - correct_pct}
    else:
        correct_vote = random.randint(55, 80)
        wrong_votes = [random.randint(5, 30) for _ in range(3)]
        total = correct_vote + sum(wrong_votes)
        wrong_pcts = [int(v / total * 100) for v in wrong_votes]
        wrong_idxs = [i for i in range(4) if i != correct]
        percents = {correct: 100 - sum(wrong_pcts)}
        for idx, pct in zip(wrong_idxs, wrong_pcts):
            percents[idx] = pct

    st.session_state.audience = percents
    st.session_state.audience_used = True


def lock_answer(option_index):
    st.session_state.chosen = option_index
    st.session_state.phase = "locked"


def walk_away():
    st.session_state.end_kind = "walk"
    st.session_state.end_message = f"You walked away with ₦{st.session_state.money_won:,}"
    st.session_state.phase = "game_over"


def evaluate_answer():
    qn = st.session_state.question_number
    q = current_question()

    if st.session_state.chosen == q["correct"]:
        st.session_state.money_won = PRIZES[qn + 1]
        st.session_state.question_number += 1
        st.session_state.feedback = f"✅ Correct! You now have **₦{st.session_state.money_won:,}**"
        reset_question_state()

        if st.session_state.question_number >= len(st.session_state.questions):
            st.session_state.end_kind = "won"
            st.session_state.end_message = "You answered every question correctly!"
            st.session_state.phase = "game_over"
        else:
            st.session_state.phase = "playing"
    else:
        correct_letter = LETTERS[q["correct"]]
        correct_text = q["options"][q["correct"]]
        st.session_state.end_kind = "wrong"
        st.session_state.end_message = (
            f"❌ Wrong! The correct answer was {correct_letter}) {correct_text}\n\n"
            f"You leave with **₦{st.session_state.money_won:,}**"
        )
        st.session_state.phase = "game_over"


# ----------------------------------------------------------------------------
# UI pieces
# ----------------------------------------------------------------------------
def render_ladder():
    qn = st.session_state.question_number
    lines = []
    for level in range(len(PRIZES) - 1, 0, -1):
        text = f"Q{level} · ₦{PRIZES[level]:,}"
        if level == qn + 1:
            text = f"**▶ {text}**"
        elif level <= qn:
            text = f"✅ {text}"
        lines.append(f"- {text}")
    st.sidebar.markdown("### Prize ladder\n" + "\n".join(lines))
    st.sidebar.markdown(f"**Current winnings:** ₦{st.session_state.money_won:,}")


def render_question(locked):
    qn = st.session_state.question_number
    q = current_question()

    st.markdown(f"**Question {qn + 1}**  –  You can win **₦{PRIZES[qn + 1]:,}**")
    st.markdown(f"### {q['question']}")

    for i in range(4):
        if i in st.session_state.hidden:
            st.button("───", key=f"opt_{qn}_{i}", disabled=True, use_container_width=True)
        else:
            label = f"{LETTERS[i]}) {q['options'][i]}"
            if locked and st.session_state.chosen == i:
                label = "🔒 " + label
            st.button(
                label,
                key=f"opt_{qn}_{i}",
                disabled=locked,
                on_click=lock_answer,
                args=(i,),
                use_container_width=True,
            )

    if st.session_state.audience:
        st.markdown("**Audience says...**")
        rows = [
            f"{LETTERS[i]} → {st.session_state.audience[i]}%"
            for i in range(4)
            if i in st.session_state.audience and i not in st.session_state.hidden
        ]
        st.markdown("\n\n".join(rows))

    lifelines = []
    if not st.session_state.fifty_used:
        lifelines.append("50:50")
    if not st.session_state.audience_used:
        lifelines.append("Audience")
    if lifelines:
        st.caption("Lifelines left: " + " ".join(lifelines))

    col1, col2, col3 = st.columns(3)
    col1.button(
        "50:50",
        key="btn_fifty",
        disabled=locked or st.session_state.fifty_used,
        on_click=use_fifty,
        use_container_width=True,
    )
    col2.button(
        "Ask the Audience",
        key="btn_audience",
        disabled=locked or st.session_state.audience_used,
        on_click=use_audience,
        use_container_width=True,
    )
    col3.button(
        "Walk away",
        key="btn_walk",
        disabled=locked,
        on_click=walk_away,
        use_container_width=True,
    )


