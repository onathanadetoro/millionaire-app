def main():
    init_state()

    st.title("💰 Who Wants To Be A Millionaire?")
    st.caption("Python version – Easy mode")

    phase = st.session_state.phase

    # --- Setup phase ---
    if phase == "setup":
        st.write("Hi! Today you can become a millionaire... in play money 😄")
        name = st.text_input("What is your name?")
        if st.button("Start Game", type="primary"):
            start_game(name.strip() or "Player")
            st.rerun()

    # --- Playing phase ---
    elif phase == "playing":
        render_ladder()
        st.write(f"Welcome **{st.session_state.name}**! Let's play!")
        if st.session_state.feedback:
            st.success(st.session_state.feedback)
            st.session_state.feedback = ""
        render_question(locked=False)

    # --- Answer locked in ---
    elif phase == "locked":
        render_ladder()
        st.write(f"Welcome **{st.session_state.name}**! Let's play!")
        render_question(locked=True)
        st.info("Final answer locking in...")
        time.sleep(2)
        evaluate_answer()
        st.rerun()

    # --- Game over ---
    elif phase == "game_over":
        money = st.session_state.money_won
        kind = st.session_state.end_kind

        if kind == "wrong":
            st.error(st.session_state.end_message)
        elif kind == "won":
            st.success(st.session_state.end_message)
        else:
            st.info(st.session_state.end_message)

        st.divider()
        st.subheader(f"Game finished, {st.session_state.name}!")
        st.markdown(f"You won: **₦{money:,}** 🎉")

        if money >= 1_000_000:
            st.success("MILLIONAIRE!!! 🤑🏆")
        elif money > 0:
            st.write("Great job! You earned some money 😊")
        else:
            st.write("Never mind... try again! You'll do better next time 💪")

        st.button(
            "Play Again",
            type="primary",
            on_click=start_game,
            args=(st.session_state.name,),
        )


main()